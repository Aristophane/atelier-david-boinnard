let currentLang = 'fr';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (lang === 'fr' || lang === 'en') {
    currentLang = lang;
    localStorage.setItem('db_lang', lang);
    applyTranslations();
  }
}

export function initI18n() {
  const saved = localStorage.getItem('db_lang');
  if (saved === 'en' || saved === 'fr') {
    currentLang = saved;
  }
  applyTranslations();
}

export function applyTranslations() {
  const t = translations[currentLang];
  document.documentElement.lang = currentLang;
  
  // Set lang button active states
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === currentLang));
  });
  
  // Replace elements with data-i18n="key.subkey"
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const keyPath = el.dataset.i18n.split('.');
    let val = t;
    for (const key of keyPath) {
      if (val && val[key] !== undefined) {
        val = val[key];
      } else {
        val = null;
        break;
      }
    }
    if (val !== null) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = val;
      } else {
        el.innerHTML = val;
      }
    }
  });

  // Workshop description toggle if present
  const atelierDesc = document.getElementById('atelier-main-text');
  if (atelierDesc) {
    if (currentLang === 'en') {
      atelierDesc.innerHTML = `
        <p>Since 1980, the workshop has been producing historical instruments adapted to the needs of musicians.</p>
        <div class="atelier-highlight-box">
          David Boinnard engages in organological research in the areas of instrumental production that have yet to be explored: from the restitution of small medieval keyboards played together to the production of harpsichords equipped with MIDI systems that meet the needs of the current scene.
        </div>
        <p>The level of skills acquired allows the workshop to establish itself as a reference in specific areas (from very early historical models to the most contemporary innovations) and to contribute to the advance of musicological and organological research in the field of keyboard instruments. From the studio to life on stage, David Boinnard brings life and accompanies the harpsichord. Medieval, Renaissance, Baroque and contemporary music meet and share the ultimate purpose of the instrument: music.</p>
        <p>Once finished, the harpsichord starts another life in the hands of the musician.</p>
      `;
    } else {
      atelierDesc.innerHTML = `
        <p>Depuis 1980, l'atelier réalise des instruments historiques adaptés aux exigences et à la sensibilité des musiciens.</p>
        <div class="atelier-highlight-box">
          David Boinnard s'engage dans la recherche organologique dans des domaines de la facture instrumentale encore peu explorés : de la restitution de petits claviers médiévaux joués en ensemble à la réalisation de clavecins équipés de systèmes MIDI répondant aux besoins de la scène actuelle.
        </div>
        <p>Le niveau de compétences acquis permet à l'atelier de s'imposer comme référence dans certains domaines précis (de l'archaïque au contemporain) et de contribuer à faire progresser l'état de la recherche musicologique et organologique dans le domaine du clavecin. De l'atelier à la vie sur scène, David Boinnard donne vie et accompagne l'instrument. Musiques médiévales, Renaissance, baroques et contemporaines s'y croisent et partagent la finalité de l'instrument : la musique.</p>
        <p>Une fois achevé, le clavecin commence une autre vie entre les mains du musicien.</p>
      `;
    }
  }

  // Access routes toggle
  const accessTaxi = document.getElementById('access-taxi-text');
  const accessTransport = document.getElementById('access-transport-text');
  if (accessTaxi && accessTransport) {
    if (currentLang === 'en') {
      accessTaxi.textContent = "10' from Lille TGV Station (Europe / Flandres), 10' from Lille - Lesquin Airport.";
      accessTransport.textContent = "Subway Line 2 (Porte de Douai station), Bus connection Line 15 / 57 (Ronchin République stop).";
    } else {
      accessTaxi.textContent = "10 min de la gare Lille TGV (Flandres / Europe), 10 min de l'aéroport Lille - Lesquin.";
      accessTransport.textContent = "Métro Ligne 2 (arrêt Porte de Douai), Correspondance Bus 15 / 57 (arrêt Ronchin République).";
    }
  }
}
